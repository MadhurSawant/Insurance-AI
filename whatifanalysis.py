"""
What-if analysis and model connection for the Insurance AI application.

This module loads the model.pkl generated by the Colab training notebook
and provides:

1. Normal premium prediction
2. Prediction uncertainty
3. Approximate 95% prediction interval
4. What-if scenario comparison
5. Human-readable feature sensitivity/explanation

Expected model.pkl structure:

{
    "prediction_pipeline": Pipeline(...),
    "preprocessor": ColumnTransformer(...),
    "model": XGBRegressor(...),
    "uncertainty_models": [...],
    "best_params": {...},
    ...
}
"""

import os
import pickle

import numpy as np
import pandas as pd


# ============================================================
# Compatibility patch: sklearn 1.6.x → 1.7.x
# ============================================================
# model.pkl was saved with sklearn 1.6.1 which used
# _RemainderColsList internally in ColumnTransformer.
# sklearn 1.7+ removed this class, breaking pickle.load().
# This stub restores it so the saved artifact can be loaded.
# ============================================================
try:
    import sklearn.compose._column_transformer as _skct
    if not hasattr(_skct, "_RemainderColsList"):
        class _RemainderColsList(list):
            """Compatibility stub for sklearn < 1.7 pickled models."""
            def __reduce__(self):
                return (self.__class__, (list(self),))
        _skct._RemainderColsList = _RemainderColsList
except Exception:
    pass


FEATURES = [
    "age",
    "sex",
    "bmi",
    "children",
    "smoker",
    "region",
]

DISPLAY_NAMES = {
    "age": "Age",
    "sex": "Sex",
    "bmi": "BMI",
    "children": "Children",
    "smoker": "Smoking",
    "region": "Region",
}

# Reasonable one-variable perturbations used for local sensitivity.
# These are model sensitivity tests, not causal medical effects.
STEP_VALUES = {
    "age": 5,
    "bmi": 2.0,
    "children": 1,
}


def _as_dataframe(patient):
    """Convert a patient dictionary into the exact feature DataFrame."""

    return pd.DataFrame(
        [{
            "age": patient["age"],
            "sex": patient["sex"],
            "bmi": patient["bmi"],
            "children": patient["children"],
            "smoker": patient["smoker"],
            "region": patient["region"],
        }],
        columns=FEATURES,
    )


TARGET_OFFSET = 13270.422


def _predict_with_pipeline(pipeline, patient):
    """Point prediction using the saved full preprocessing + model pipeline."""

    X = _as_dataframe(patient)
    return float(pipeline.predict(X)[0]) + TARGET_OFFSET


def _predict_with_uncertainty_models(
    preprocessor,
    uncertainty_models,
    patient,
):
    """
    Generate predictions from all uncertainty models.

    The models in the user's Colab notebook are trained on transformed
    feature arrays, so raw patient data must first pass through the saved
    preprocessor.
    """

    X = _as_dataframe(patient)
    X_transformed = preprocessor.transform(X)

    predictions = (
        np.asarray(
            [
                model.predict(X_transformed)[0]
                for model in uncertainty_models
            ],
            dtype=float,
        )
        + TARGET_OFFSET
    )

    mean_prediction = float(np.mean(predictions))
    uncertainty = float(np.std(predictions))

    # Approximate normal 95% interval (non-negative premium).
    lower = max(0.0, float(mean_prediction - 1.96 * uncertainty))
    upper = float(mean_prediction + 1.96 * uncertainty)

    return {
        "prediction": mean_prediction,
        "uncertainty": uncertainty,
        "lower": lower,
        "upper": upper,
        "confidence_level": 0.95,
        "individual_predictions": predictions.tolist(),
    }


def build_prediction_from_artifact(artifact, patient):
    """Compatibility helper for direct artifact-based predictions."""

    pipeline = artifact["prediction_pipeline"]
    preprocessor = artifact["preprocessor"]
    uncertainty_models = artifact["uncertainty_models"]

    result = _predict_with_uncertainty_models(
        preprocessor,
        uncertainty_models,
        patient,
    )

    # Use the full pipeline's point prediction as the primary prediction
    # because that is the final trained model saved by the notebook.
    result["prediction"] = _predict_with_pipeline(
        pipeline,
        patient,
    )

    result["lower"] = max(0.0, float(
        result["prediction"] -
        1.96 * result["uncertainty"]
    ))

    result["upper"] = float(
        result["prediction"] +
        1.96 * result["uncertainty"]
    )

    result["lower_95"] = result["lower"]
    result["upper_95"] = result["upper"]
    result["premium"] = result["prediction"]

    return result


class InsuranceWhatIfAnalyzer:

    def __init__(self, model_path):
        if not os.path.exists(model_path):
            raise FileNotFoundError(
                f"Model file not found: {model_path}"
            )

        with open(model_path, "rb") as file:
            self.artifact = pickle.load(file)

        self.pipeline = self.artifact.get("prediction_pipeline")
        self.preprocessor = self.artifact.get("preprocessor")
        self.model = self.artifact.get("model")
        self.uncertainty_models = self.artifact.get(
            "uncertainty_models",
            [],
        )

        if self.pipeline is None:
            raise ValueError(
                "model.pkl does not contain 'prediction_pipeline'. "
                "Regenerate model.pkl using the supplied Colab notebook."
            )

        if self.preprocessor is None:
            raise ValueError(
                "model.pkl does not contain 'preprocessor'."
            )

        if not self.uncertainty_models:
            raise ValueError(
                "model.pkl does not contain 'uncertainty_models'."
            )

    # ------------------------------------------------------------------
    # Main prediction
    # ------------------------------------------------------------------

    def predict(self, patient):
        """Return premium, uncertainty and approximate 95% interval."""

        return build_prediction_from_artifact(
            self.artifact,
            patient,
        )

    # ------------------------------------------------------------------
    # What-if comparison
    # ------------------------------------------------------------------

    def compare(self, baseline_patient, scenario_patient):
        """
        Compare two patient profiles.

        Returns:
            baseline prediction
            scenario prediction
            absolute premium change
            percentage change
            changed fields and their individual effects
        """

        baseline = self.predict(baseline_patient)
        scenario = self.predict(scenario_patient)

        premium_change = (
            scenario["prediction"] -
            baseline["prediction"]
        )

        if abs(baseline["prediction"]) > 1e-9:
            percent_change = (
                premium_change /
                baseline["prediction"]
            ) * 100.0
        else:
            percent_change = 0.0

        changes = self._calculate_changed_features(
            baseline_patient,
            scenario_patient,
        )

        return {
            "baseline": baseline,
            "scenario": scenario,
            "premium_change": float(premium_change),
            "percent_change": float(percent_change),
            "changes": changes,
        }

    def _calculate_changed_features(
        self,
        baseline_patient,
        scenario_patient,
    ):
        """
        Explain each changed field by changing that field individually
        from baseline to scenario and measuring the model response.

        This is a local model-sensitivity explanation, not a causal claim.
        """

        changes = []

        for feature in FEATURES:

            baseline_value = baseline_patient[feature]
            scenario_value = scenario_patient[feature]

            if baseline_value == scenario_value:
                continue

            individual_scenario = dict(baseline_patient)
            individual_scenario[feature] = scenario_value

            baseline_prediction = self.predict(
                baseline_patient
            )["prediction"]

            individual_prediction = self.predict(
                individual_scenario
            )["prediction"]

            effect = (
                individual_prediction -
                baseline_prediction
            )

            direction = (
                "increase"
                if effect > 0
                else "decrease"
                if effect < 0
                else "neutral"
            )

            changes.append(
                {
                    "feature": feature,
                    "name": DISPLAY_NAMES[feature],
                    "from": baseline_value,
                    "to": scenario_value,
                    "effect": float(effect),
                    "direction": direction,
                }
            )

        # Largest absolute model effect first.
        changes.sort(
            key=lambda item: abs(item["effect"]),
            reverse=True,
        )

        return changes

    # ------------------------------------------------------------------
    # Explain current prediction
    # ------------------------------------------------------------------

    def explain_prediction(self, patient):
        """
        Produce template-friendly local sensitivity explanations.

        For each feature, compare the current prediction against a nearby
        reference value. This avoids pretending that the model itself
        provides causal explanations.
        """

        current_prediction = self.predict(
            patient
        )["prediction"]

        factors = []

        for feature in FEATURES:

            alternative = dict(patient)

            if feature == "age":
                alternative["age"] = (
                    patient["age"] + STEP_VALUES["age"]
                )

            elif feature == "bmi":
                alternative["bmi"] = max(
                    10.0,
                    patient["bmi"] + STEP_VALUES["bmi"],
                )

            elif feature == "children":
                alternative["children"] = (
                    patient["children"] + STEP_VALUES["children"]
                )

            elif feature == "smoker":
                alternative["smoker"] = (
                    "no"
                    if patient["smoker"] == "yes"
                    else "yes"
                )

            elif feature == "sex":
                alternative["sex"] = (
                    "female"
                    if patient["sex"] == "male"
                    else "male"
                )

            elif feature == "region":
                alternative["region"] = self._next_region(
                    patient["region"]
                )

            alternative_prediction = self.predict(
                alternative
            )["prediction"]

            effect = (
                alternative_prediction -
                current_prediction
            )

            absolute_effect = abs(effect)

            if absolute_effect >= 500:
                impact = "High"
            elif absolute_effect >= 150:
                impact = "Medium"
            else:
                impact = "Low"

            if effect > 1:
                direction = "positive"
            elif effect < -1:
                direction = "negative"
            else:
                direction = "neutral"

            factors.append(
                {
                    "name": DISPLAY_NAMES[feature],
                    "impact": impact,
                    "direction": direction,
                    "value": patient[feature],
                    "effect": float(effect),
                    "explanation": (
                        f"A nearby model scenario changes "
                        f"the predicted premium by "
                        f"${abs(effect):,.2f}."
                    ),
                }
            )

        factors.sort(
            key=lambda item: abs(item["effect"]),
            reverse=True,
        )

        return factors

    @staticmethod
    def _next_region(region):
        regions = [
            "southwest",
            "southeast",
            "northwest",
            "northeast",
        ]

        try:
            index = regions.index(region)
        except ValueError:
            return "southwest"

        return regions[
            (index + 1) % len(regions)
        ]
