"""
ExplainAI.py
------------
SHAP-based explainability module for the Insurance AI application.

This module is intentionally separate from app.py and whatifanalysis.py.

It loads the model artifact generated by the Colab training notebook and
provides:

1. Global SHAP feature importance
2. Local SHAP explanation for one patient
3. SHAP waterfall-compatible values
4. Human-readable feature explanations
5. A prediction explanation for the Flask UI

Expected model artifact:
    artifacts/model.pkl

The model.pkl should contain:
    - prediction_pipeline
    - preprocessor
    - model
    - uncertainty_models
    - feature_columns
    - numerical_features
    - categorical_features

Install SHAP:
    pip install shap
"""

import os
import pickle

import numpy as np
import pandas as pd
import shap


# ============================================================
# Compatibility patch: sklearn 1.6.x → 1.7.x
# ============================================================
# model.pkl was saved with sklearn 1.6.1 which used
# _RemainderColsList internally in ColumnTransformer.
# sklearn 1.7+ removed this class, breaking pickle.load().
# This stub restores it so the saved artifact can be loaded.
# ============================================================
try:
    import sklearn.compose._column_transformer as _skct
    if not hasattr(_skct, "_RemainderColsList"):
        class _RemainderColsList(list):
            """Compatibility stub for sklearn < 1.7 pickled models."""
            def __reduce__(self):
                return (self.__class__, (list(self),))
        _skct._RemainderColsList = _RemainderColsList
except Exception:
    pass


FEATURES = [
    "age",
    "sex",
    "bmi",
    "children",
    "smoker",
    "region",
]

DISPLAY_NAMES = {
    "age": "Age",
    "sex": "Sex",
    "bmi": "BMI",
    "children": "Children",
    "smoker": "Smoking",
    "region": "Region",
}


class InsuranceExplainAI:
    """
    SHAP explanation engine for the trained XGBoost insurance model.

    The XGBoost model itself receives the transformed numerical matrix,
    therefore SHAP is calculated on the transformed feature space and
    then mapped back to readable feature names.
    """

    def __init__(self, model_path):
        if not os.path.exists(model_path):
            raise FileNotFoundError(
                f"Model file not found: {model_path}"
            )

        with open(model_path, "rb") as file:
            self.artifact = pickle.load(file)

        self.model = self.artifact.get("model")
        self.preprocessor = self.artifact.get("preprocessor")
        self.pipeline = self.artifact.get("prediction_pipeline")

        if self.model is None:
            raise ValueError(
                "model.pkl does not contain 'model'."
            )

        if self.preprocessor is None:
            raise ValueError(
                "model.pkl does not contain 'preprocessor'."
            )

        # ---------------------------------------------------------------
        # Get transformed feature names
        # ---------------------------------------------------------------

        self.feature_names = self._get_feature_names()

        # ---------------------------------------------------------------
        # SHAP explainer
        # ---------------------------------------------------------------

        self.explainer = shap.TreeExplainer(
            self.model
        )

    # ===================================================================
    # Feature name handling
    # ===================================================================

    def _get_feature_names(self):
        """
        Get the feature names after ColumnTransformer preprocessing.

        For the user's dataset this should produce names similar to:

            OneHotEncoder__sex_female
            OneHotEncoder__sex_male
            OneHotEncoder__smoker_no
            OneHotEncoder__smoker_yes
            OneHotEncoder__region_northeast
            ...
            StandardScaler__age
            StandardScaler__bmi
            StandardScaler__children
        """

        try:
            names = self.preprocessor.get_feature_names_out()

            clean_names = []

            for name in names:

                # Remove transformer prefixes
                name = name.replace(
                    "OneHotEncoder__",
                    ""
                )

                name = name.replace(
                    "StandardScaler__",
                    ""
                )

                clean_names.append(name)

            return clean_names

        except Exception:

            # Fallback for older sklearn versions.
            return [
                f"feature_{i}"
                for i in range(
                    self.model.n_features_in_
                )
            ]

    # ===================================================================
    # Input preparation
    # ===================================================================

    @staticmethod
    def _patient_dataframe(patient):
        """
        Convert a patient dictionary into the original feature DataFrame.
        """

        return pd.DataFrame(
            [{
                "age": patient["age"],
                "sex": patient["sex"],
                "bmi": patient["bmi"],
                "children": patient["children"],
                "smoker": patient["smoker"],
                "region": patient["region"],
            }],
            columns=FEATURES,
        )

    def transform_patient(self, patient):
        """
        Transform raw patient data using the exact preprocessing object
        used during model training.
        """

        patient_df = self._patient_dataframe(
            patient
        )

        return self.preprocessor.transform(
            patient_df
        )

    TARGET_OFFSET = 13270.422

    # ===================================================================
    # Prediction
    # ===================================================================

    def predict(self, patient):
        """
        Return the model prediction for a patient.
        """

        X_transformed = self.transform_patient(
            patient
        )

        prediction = self.model.predict(
            X_transformed
        )[0]

        return float(prediction) + self.TARGET_OFFSET

    # ===================================================================
    # Local SHAP explanation
    # ===================================================================

    def explain_patient(self, patient):
        """
        Generate a complete SHAP explanation for one patient.

        Returns a dictionary that can directly be passed to a Flask
        Jinja template or returned through a JSON API.
        """

        X_transformed = self.transform_patient(
            patient
        )

        shap_values = self.explainer(
            X_transformed
        )

        values = np.asarray(
            shap_values.values
        )

        if values.ndim == 3:
            # Defensive handling for unexpected multi-output format.
            values = values[:, :, 0]

        values = values[0]

        base_value = np.asarray(
            shap_values.base_values
        )

        if base_value.ndim > 1:
            base_value = base_value[0]

        base_value = float(
            np.asarray(base_value).reshape(-1)[0]
        ) + self.TARGET_OFFSET

        prediction = self.predict(
            patient
        )

        # ---------------------------------------------------------------
        # Build feature-level explanations
        # ---------------------------------------------------------------

        feature_explanations = []

        for feature_name, shap_value in zip(
            self.feature_names,
            values
        ):

            readable_name = self._readable_feature_name(
                feature_name
            )

            feature_value = self._get_feature_value(
                patient,
                feature_name
            )

            shap_value = float(shap_value)

            if shap_value > 0:
                direction = "increases"
            elif shap_value < 0:
                direction = "decreases"
            else:
                direction = "neutral"

            feature_explanations.append(
                {
                    "feature": feature_name,
                    "name": readable_name,
                    "value": feature_value,
                    "shap_value": shap_value,
                    "absolute_shap": abs(shap_value),
                    "direction": direction,
                    "impact": self._impact_level(
                        abs(shap_value)
                    ),
                    "effect_text": (
                        f"{readable_name} "
                        f"{direction} the predicted "
                        f"premium by approximately "
                        f"₹{abs(shap_value):,.2f}."
                    ),
                }
            )

        # Largest impact first.
        feature_explanations.sort(
            key=lambda item: item["absolute_shap"],
            reverse=True,
        )

        return {
            "prediction": prediction,

            "base_value": base_value,

            "shap_values": feature_explanations,

            "top_factors": feature_explanations[:6],

            "feature_names": self.feature_names,

            "raw_shap_values": values.tolist(),
        }

    # ===================================================================
    # Human-readable feature names
    # ===================================================================

    @staticmethod
    def _readable_feature_name(
        feature_name
    ):
        """
        Convert transformed feature names into UI-friendly names.

        Examples:
            smoker_yes -> Smoking (Yes)
            bmi -> BMI
            age -> Age
            region_southeast -> Region (Southeast)
        """

        name = feature_name.lower()

        if name.startswith("sex_"):
            value = feature_name.split(
                "_",
                1
            )[1]

            return (
                f"Sex ({value.title()})"
            )

        if name.startswith("smoker_"):
            value = feature_name.split(
                "_",
                1
            )[1]

            return (
                f"Smoking ({value.title()})"
            )

        if name.startswith("region_"):
            value = feature_name.split(
                "_",
                1
            )[1]

            return (
                f"Region ({value.title()})"
            )

        if name == "age":
            return "Age"

        if name == "bmi":
            return "BMI"

        if name == "children":
            return "Children"

        return feature_name

    # ===================================================================
    # Patient feature value
    # ===================================================================

    @staticmethod
    def _get_feature_value(
        patient,
        feature_name
    ):
        name = feature_name.lower()

        if name.startswith("sex_"):
            category = feature_name.split(
                "_",
                1
            )[1]

            return patient["sex"]

        if name.startswith("smoker_"):
            return patient["smoker"]

        if name.startswith("region_"):
            return patient["region"]

        if name == "age":
            return patient["age"]

        if name == "bmi":
            return patient["bmi"]

        if name == "children":
            return patient["children"]

        return "N/A"

    # ===================================================================
    # Impact classification
    # ===================================================================

    @staticmethod
    def _impact_level(
        absolute_shap
    ):
        """
        Classify SHAP magnitude for UI display.

        The thresholds are UI labels, not statistical significance.
        """

        if absolute_shap >= 500:
            return "High"

        if absolute_shap >= 150:
            return "Medium"

        return "Low"

    # ===================================================================
    # Global SHAP importance
    # ===================================================================

    def global_feature_importance(
        self,
        X_reference
    ):
        """
        Calculate mean absolute SHAP importance.

        X_reference should be the raw feature DataFrame containing:

            age
            sex
            bmi
            children
            smoker
            region

        This method transforms the reference data using the saved
        preprocessing pipeline before calculating SHAP values.
        """

        if not isinstance(
            X_reference,
            pd.DataFrame
        ):
            X_reference = pd.DataFrame(
                X_reference,
                columns=FEATURES
            )

        X_transformed = (
            self.preprocessor.transform(
                X_reference
            )
        )

        shap_values = self.explainer(
            X_transformed
        )

        values = np.asarray(
            shap_values.values
        )

        if values.ndim == 3:
            values = values[:, :, 0]

        mean_abs_shap = np.mean(
            np.abs(values),
            axis=0
        )

        result = pd.DataFrame(
            {
                "feature": self.feature_names,
                "mean_abs_shap": mean_abs_shap,
            }
        )

        result["feature_name"] = (
            result["feature"]
            .apply(
                self._readable_feature_name
            )
        )

        result = result.sort_values(
            "mean_abs_shap",
            ascending=False
        ).reset_index(
            drop=True
        )

        return result

    # ===================================================================
    # Generate SHAP plot
    # ===================================================================

    def save_waterfall_plot(
        self,
        patient,
        output_path
    ):
        """
        Save a SHAP waterfall plot for one patient.

        The generated PNG can be served by Flask from the static folder.
        """

        import matplotlib.pyplot as plt

        X_transformed = self.transform_patient(
            patient
        )

        shap_values = self.explainer(
            X_transformed
        )

        # Give the transformed row readable feature names and shift base_values
        shap_values.feature_names = (
            self.feature_names
        )
        shap_values.base_values = shap_values.base_values + self.TARGET_OFFSET

        plt.figure(
            figsize=(10, 6)
        )

        shap.plots.waterfall(
            shap_values[0],
            max_display=10,
            show=False
        )

        plt.tight_layout()

        os.makedirs(
            os.path.dirname(output_path),
            exist_ok=True
        )

        plt.savefig(
            output_path,
            dpi=150,
            bbox_inches="tight"
        )

        plt.close()

        return output_path

    def save_global_bar_plot(
        self,
        X_reference,
        output_path,
        max_display=10
    ):
        """
        Save a global SHAP bar plot.
        """

        import matplotlib.pyplot as plt

        if not isinstance(
            X_reference,
            pd.DataFrame
        ):
            X_reference = pd.DataFrame(
                X_reference,
                columns=FEATURES
            )

        X_transformed = (
            self.preprocessor.transform(
                X_reference
            )
        )

        shap_values = self.explainer(
            X_transformed
        )

        shap_values.feature_names = (
            self.feature_names
        )

        plt.figure(
            figsize=(10, 6)
        )

        shap.plots.bar(
            shap_values,
            max_display=max_display,
            show=False
        )

        plt.tight_layout()

        os.makedirs(
            os.path.dirname(output_path),
            exist_ok=True
        )

        plt.savefig(
            output_path,
            dpi=150,
            bbox_inches="tight"
        )

        plt.close()

        return output_path
